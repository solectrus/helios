module Export
  class Env
    SEPARATOR = "# #{'=' * 60}".freeze

    SECTIONS = [
      [General,      ->(_) { true }],
      [Security,     ->(_) { true }],
      [Dashboard,    ->(c) { !c.collectors_only? }],
      [Postgresql,   ->(c) { !c.collectors_only? }],
      [Influxdb,     ->(_) { true }],
      [Redis,        ->(c) { !c.collectors_only? }],
      [ReverseProxy, ->(c) { Services::Traefik.enabled?(c) }],
      [Backup,       ->(c) { !c.collectors_only? && c.configured?(:backup) }],
      [Senec,        ->(c) { Services::SenecCollector.enabled?(c) }],
      [Forecast,     ->(c) { Services::ForecastCollector.enabled?(c) }],
      [Mqtt,         ->(c) { Services::MqttCollector.enabled?(c) }],
      [Shelly,       ->(c) { Services::ShellyCollector.enabled?(c) }],
      [Ingest,       ->(c) { c.ingest_required? }],
      [Watchtower,   ->(_) { true }],
      [Sensors,      ->(_) { true }],
      [Unmanaged,    ->(_) { true }],
    ].freeze

    def initialize(configuration)
      @configuration = configuration
    end

    def to_s
      env_file = ::Env::File.new(::Env.path)
      env_file.header_comment = header_comment
      build(env_file)
      env_file.to_s
    end

    private

    attr_reader :configuration

    def build(env)
      enabled_sections.each { |section_class| section_class.new(env, configuration).call }
    end

    def enabled_sections
      SECTIONS.filter_map { |klass, enabled| klass if enabled.call(configuration) }
    end

    def header_comment
      [
        SEPARATOR,
        '# Generated by HELIOS — DO NOT EDIT MANUALLY!',
        '#',
        '# This file defines environment variables for your SOLECTRUS Docker stack.',
        '# It is regenerated whenever you apply changes in HELIOS.',
        '# Use the HELIOS web interface to modify your configuration.',
        SEPARATOR,
        '', # Blank line before first section
      ].join("\n")
    end
  end
end
