class StackBuilder
  HELIOS_MARKER = 'Generated by Helios'.freeze

  SECRET_DEFAULTS = {
    'postgres_password' => -> { SecureRandom.alphanumeric(32) },
    'secret_key_base' => -> { SecureRandom.alphanumeric(64) },
    'admin_password' => -> { SecureRandom.alphanumeric(32) },
    'influx_password' => -> { SecureRandom.alphanumeric(32) },
    'influx_org' => -> { 'solectrus' },
    'influx_bucket' => -> { 'solectrus' },
    'influx_token' => -> { SecureRandom.hex(32) },
    'helios_secret_key_base' => -> { SecureRandom.hex(64) },
  }.freeze

  def initialize(configuration)
    @configuration = configuration
  end

  def write!
    create_data_directories!
    write_compose!
    write_env!
  end

  def compose_content
    compose_builder.to_yaml
  end

  def env_content
    ensure_secrets!
    EnvContent.new(@configuration).to_s
  end

  private

  def stack_path
    Rails.configuration.helios_stack_path
  end

  def compose_builder
    @compose_builder ||= ComposeBuilder.new(@configuration)
  end

  def create_data_directories!
    compose_builder.data_directories.each do |dir|
      FileUtils.mkdir_p(File.join(stack_path, dir))
    end
  end

  def write_compose!
    backup_if_not_generated!(Compose.path)
    ::File.write(Compose.path, compose_content)
  end

  def write_env!
    backup_if_not_generated!(Env.path)
    ::File.write(Env.path, env_content)
  end

  def backup_if_not_generated!(path)
    return unless ::File.exist?(path)
    return if ::File.read(path).include?(HELIOS_MARKER)

    ::FileUtils.cp(path, "#{path}.bak")
  end

  def ensure_secrets!
    current_system = @configuration.system
    missing = SECRET_DEFAULTS.reject { |key, _| current_system[key] }
    updates = missing.transform_values(&:call)

    return if updates.empty?

    @configuration.update('system', current_system.merge(updates))
    @compose_builder = nil
  end
end
