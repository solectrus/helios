class StackBuilder
  class EnvContent
    SEPARATOR = "# #{'=' * 60}".freeze

    def initialize(configuration)
      @configuration = configuration
    end

    def to_s
      sections = [
        *file_header_lines,
        *general_section_lines,
        *security_section_lines,
        *postgresql_section_lines,
        *influxdb_section_lines,
        *helios_section_lines,
      ]
      sections.concat(reverse_proxy_section_lines) if Services::Traefik.enabled?(configuration)
      sections.concat(backup_section_lines) if Services::PostgresqlBackup.enabled?(configuration)
      sections.join("\n")
    end

    private

    attr_reader :configuration

    def system_chapter
      configuration.chapter('system')
    end

    def reverse_proxy_chapter
      configuration.chapter('reverse_proxy')
    end

    def backup_chapter
      configuration.chapter('backup')
    end

    def host_stack_path
      Rails.configuration.helios_host_stack_path
    end

    def file_header_lines
      [
        SEPARATOR,
        '# Generated by Helios — DO NOT EDIT MANUALLY!',
        '#',
        '# This file is regenerated from the Helios configuration (SQLite).',
        '# Use the Helios web interface to modify your configuration.',
        SEPARATOR,
        '',
      ]
    end

    def general_section_lines
      [
        '# --- General settings ---',
        *entry('TZ', system_chapter['timezone'],
               'Timezone for all services (IANA format, e.g. Europe/Berlin)'),
        *entry('INSTALLATION_DATE', system_chapter['installation_date'],
               'Date of first solar installation (YYYY-MM-DD) — used for statistics and charts'),
      ]
    end

    def security_section_lines
      [
        '# --- Security ---',
        *entry('ADMIN_PASSWORD', system_chapter['admin_password'],
               'Admin password for the SOLECTRUS web interface'),
        *entry('SECRET_KEY_BASE', system_chapter['secret_key_base'],
               'Rails session secret key — keep this confidential, never share it!'),
      ]
    end

    def postgresql_section_lines
      [
        '# --- PostgreSQL database ---',
        *entry('POSTGRES_PASSWORD', system_chapter['postgres_password'],
               'Database password — auto-generated, do not change after first start'),
        '',
      ]
    end

    def influxdb_section_lines
      [
        '# --- InfluxDB time-series database ---',
        *entry('INFLUX_PASSWORD', system_chapter['influx_password'],
               'Admin password — auto-generated, do not change after first start'),
        *entry('INFLUX_ORG', system_chapter['influx_org'], 'Organization name'),
        *entry('INFLUX_BUCKET', system_chapter['influx_bucket'],
               'Bucket (database) name for time-series data'),
        *entry('INFLUX_TOKEN', system_chapter['influx_token'],
               'API token with full access — auto-generated, do not change after first start'),
      ]
    end

    def helios_section_lines
      [
        '# --- Helios ---',
        *entry('HELIOS_HOST_STACK_PATH', host_stack_path,
               'Path on the Docker host where stack files are stored'),
        *entry('HELIOS_SECRET_KEY_BASE', system_chapter['helios_secret_key_base'],
               'Helios session secret key — auto-generated, do not change'),
      ]
    end

    def reverse_proxy_section_lines
      [
        '# --- Reverse Proxy (Traefik) ---',
        *entry('APP_DOMAIN', reverse_proxy_chapter['app_domain'],
               'Domain for HTTPS access via Traefik'),
        *entry('LETSENCRYPT_EMAIL', Services::Traefik.letsencrypt_email(configuration),
               "Email for Let's Encrypt certificate notifications"),
      ]
    end

    def backup_section_lines
      [
        '# --- S3 Backup ---',
        *entry('AWS_ACCESS_KEY_ID', backup_chapter['aws_access_key_id'],
               'AWS access key for S3 backup'),
        *entry('AWS_SECRET_ACCESS_KEY', backup_chapter['aws_secret_access_key'],
               'AWS secret key — keep this confidential!'),
        *entry('AWS_REGION', backup_chapter['aws_region'],
               'AWS region for S3 bucket'),
        *entry('AWS_BUCKET', backup_chapter['aws_bucket'],
               'S3 bucket name for backups'),
      ]
    end

    # Returns three lines: a comment, the key=value assignment, and a blank line.
    def entry(key, value, comment)
      ["# #{comment}", "#{key}=#{value}", '']
    end
  end
end
